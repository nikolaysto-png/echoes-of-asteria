export const GLYPH_W = 5;
export const GLYPH_H = 7;
const MISSING = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'];

function glyphFor(ch) {
  return G[ch] || G[ch.toUpperCase()] || G[ch.toLowerCase()] || MISSING;
}

/** Draw text. Scale 1 is the native body size; shadow is off by default. */
export function drawText(ctx, str, x, y, opts = {}) {
  const scale = opts.scale || 1;
  const color = opts.color || '#0f380f';
  const spacing = opts.spacing != null ? opts.spacing : 1;
  const lineHeight = opts.lineHeight || 9;
  const align = opts.align || 'left';
  const maxWidth = opts.maxWidth || 0;
  const lines = wrapText(str, maxWidth, scale, spacing);
  const totalW = measureLines(lines, scale, spacing);
  let ox = x;
  if (align === 'center') ox = x - totalW / 2;
  else if (align === 'right') ox = x - totalW;

  for (let li = 0; li < lines.length; li++) {
    let cx = ox;
    const line = lines[li];
    for (const ch of line) {
      const glyph = glyphFor(ch);
      for (let row = 0; row < GLYPH_H; row++) {
        for (let col = 0; col < GLYPH_W; col++) {
          if (glyph[row][col] === '#') {
            ctx.fillStyle = color;
            ctx.fillRect(Math.round(cx + col * scale), Math.round(y + li * lineHeight * scale + row * scale), scale, scale);
          }
        }
      }
      cx += (GLYPH_W + spacing) * scale;
    }
  }
  return { lines: lines.length, width: totalW };
}

export function measureText(str, scale = 1, spacing = 1) {
  let max = 0;
  for (const line of String(str ?? '').split('\n')) {
    max = Math.max(max, line.length * (GLYPH_W + spacing) * scale - spacing * scale);
  }
  return Math.max(0, max);
}

function measureLines(lines, scale, spacing) {
  let max = 0;
  for (const line of lines) {
    max = Math.max(max, line.length * (GLYPH_W + spacing) * scale - spacing * scale);
  }
  return Math.max(0, max);
}

/** Word wrap using native font metrics. Newlines are preserved. */
export function wrapText(str, maxWidth, scale = 1, spacing = 1) {
  const source = String(str ?? '');
  if (!maxWidth) return source.split('\n');
  const maxChars = Math.max(1, Math.floor((maxWidth + spacing * scale) / ((GLYPH_W + spacing) * scale)));
  const out = [];
  for (const paragraph of source.split('\n')) {
    if (paragraph.length === 0) { out.push(''); continue; }
    const words = paragraph.split(' ');
    let cur = '';
    for (const word of words) {
      if (!cur) cur = word;
      else if (cur.length + 1 + word.length <= maxChars) cur += ' ' + word;
      else { out.push(cur); cur = word; }
      while (cur.length > maxChars) {
        out.push(cur.slice(0, maxChars));
        cur = cur.slice(maxChars);
      }
    }
    if (cur.length) out.push(cur);
  }
  return out.length ? out : [''];
}
